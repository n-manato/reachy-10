#!/usr/bin/env python3
"""到着時刻を測るための「クリック」音源を作る。

    python tools/make_pingtest.py

なぜ `make_calibration.py` では測れなかったか
--------------------------------------------
あちらの測定音は**帯域制限ノイズ**（300-6000Hz、250ms）。台ごとに別のシードを
使って互いに直交させてあり、PC 上の相関としては理想的な設計だった。

だが Reachy Mini のマイクは音声用の前段 DSP を通る ―― エコー除去・**雑音抑圧**・
AGC。**雑音抑圧は定常的なノイズを消すためのもので、帯域制限ノイズはまさに
その標的**。実測（7箇所から録音）で、波形相関は corr 0.010-0.020（=無相関）、
包絡線でも3回の再現が 100-280ms ばらついて使い物にならなかった。

ここでは信号を変える:
  * **トーン**（1.6-3.2kHz の減衰正弦）―― 雑音抑圧が消さない
  * **鋭い立ち上がり**（1ms）―― 到着時刻が一意に決まる
  * **短い**（35ms）―― 残響と重ならない
  * 台ごとに違う周波数 ―― 取り違えを検出できる
発音の時刻割りは calib と同じ（1.5秒間隔、9台×3周）ので、どの瞬間も
鳴っているのは1台だけ。
"""

from __future__ import annotations

import argparse
import sys
import wave
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np  # noqa: E402

SR = 16000
GAP = 1.5
ROUNDS = 8          # 中央値を安定させるための繰り返し回数
FIRST = 1.0
CLICK_S = 0.035
# 台ごとの周波数。倍音関係を避けるため等比ではなく素直に散らす。
FREQS = [1600, 1780, 1980, 2200, 2450, 2720, 3020, 3360, 3730]


def click(f: float) -> np.ndarray:
    n = int(CLICK_S * SR)
    t = np.arange(n) / SR
    y = np.sin(2 * np.pi * f * t) * np.exp(-t / 0.006)
    a = int(0.001 * SR)                      # 1ms の立ち上がり
    y[:a] *= np.sin(np.linspace(0, np.pi / 2, a)) ** 2
    y[-a:] *= np.cos(np.linspace(0, np.pi / 2, a)) ** 2
    return y * 0.95


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="songs/pingtest")
    args = ap.parse_args()
    root = Path(__file__).resolve().parent.parent
    out = (root / args.out) if not Path(args.out).is_absolute() else Path(args.out)
    (out / "audio").mkdir(parents=True, exist_ok=True)

    n_rob = len(FREQS)
    total = FIRST + GAP * n_rob * ROUNDS + 1.5
    print(f"click: {CLICK_S*1000:.0f}ms の減衰正弦、立ち上がり 1ms / "
          f"{n_rob}台 x {ROUNDS}周 / {total:.1f}s")
    for k, f in enumerate(FREQS):
        x = np.zeros(int(total * SR))
        c = click(f)
        times = [FIRST + GAP * (k + n_rob * r) for r in range(ROUNDS)]
        for t in times:
            i = int(t * SR)
            x[i:i + len(c)] += c
        w = wave.open(str(out / "audio" / f"r{k+1:02d}.wav"), "wb")
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
        st = np.repeat((np.clip(x, -1, 1) * 32767).astype("<i2"), 2)
        w.writeframes(st.tobytes()); w.close()
        print(f"  r{k+1:02d}  {f:>5} Hz   sounds at " +
              ", ".join(f"{t:.1f}" for t in times) + " s")

    bars = int(total * 100 / 60 / 4)
    y = ["# generated by tools/make_pingtest.py",
         "#",
         "# 到着時刻の測定専用。**一切動かない**（全パート kind: idle）。",
         "# 測定音はトーン状のクリック ―― 帯域制限ノイズだと実機のマイクの",
         "# 雑音抑圧に消される（tools/make_pingtest.py の docstring を参照）。",
         "song:", "  name: pingtest", '  title: "Arrival-time ping test"',
         "  bpm: 100", "  meter: [4, 4]", f"  bars: {bars}",
         "  lead_in_s: 0.5", "  tail_s: 0.5", "", "parts:"]
    for k in range(n_rob):
        y += [f"  r{k+1:02d}:", "    kind: idle", "    instrument: pingtest",
              f"    audio: r{k+1:02d}.wav"]
    y += ["", "cast:"] + [f"  r{k+1:02d}: r{k+1:02d}" for k in range(n_rob)]
    (out / "song.yaml").write_text("\n".join(y) + "\n", encoding="utf-8")
    print(f"\nwrote: {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
